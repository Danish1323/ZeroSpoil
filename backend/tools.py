import os
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from datetime import datetime, timezone
from fpdf import FPDF
from typing import Dict, Any
from backend.database import db

MANIFEST_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "static", "manifests"))
os.makedirs(MANIFEST_DIR, exist_ok=True)

class FSSAIPDF(FPDF):
    def header(self):
        self.set_fill_color(30, 41, 59)
        self.rect(0, 0, 210, 24, 'F')
        self.set_font('Helvetica', 'B', 14)
        self.set_text_color(255, 255, 255)
        self.cell(0, 10, 'FSSAI SCHEDULE-I SURPLUS FOOD RESCUE MANIFEST', 0, 1, 'C')
        self.set_font('Helvetica', '', 8)
        self.cell(0, 4, 'Government of India Food Safety & Standards Compliance Certificate', 0, 1, 'C')
        self.ln(8)

    def footer(self):
        self.set_y(-18)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, f'Generated by ZeroSpoil Automated Safety Engine - Page {self.page_no()}', 0, 0, 'C')

def generate_fssai_manifest(manifest_id: str, batch: Dict[str, Any], partner: Dict[str, Any]) -> str:
    """Generates official FSSAI Surplus Handover PDF manifest"""
    pdf = FSSAIPDF()
    pdf.add_page()
    pdf.set_text_color(33, 37, 41)

    pdf.set_font('Helvetica', 'B', 12)
    pdf.cell(0, 8, f"Certificate No: MANIFEST-{manifest_id}", 0, 1, 'L')
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(0, 6, f"Generated At: {datetime.now(timezone.utc).strftime('%d-%b-%Y %H:%M:%S UTC')}", 0, 1, 'L')
    pdf.ln(4)

    # Details Box
    pdf.set_fill_color(243, 244, 246)
    pdf.rect(10, pdf.get_y(), 190, 62, 'F')
    
    pdf.set_xy(14, pdf.get_y() + 4)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.cell(60, 6, "Donor Merchant / Store:", 0, 0)
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(120, 6, str(batch.get("merchant_name", "FreshMart Supermarket - Panvel")), 0, 1)

    pdf.set_x(14)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.cell(60, 6, "Recipient Rescue Partner:", 0, 0)
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(120, 6, f"{partner.get('name', 'Community Food Bank')} ({partner.get('type', 'NGO')})", 0, 1)

    pdf.set_x(14)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.cell(60, 6, "SKU Name / Batch Code:", 0, 0)
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(120, 6, f"{batch.get('sku_name', 'Unknown Item')} [{batch.get('batch_id', 'N/A')}]", 0, 1)

    pdf.set_x(14)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.cell(60, 6, "Quantity & Unit:", 0, 0)
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(120, 6, f"{batch.get('quantity', 0)} {batch.get('unit', 'units')}", 0, 1)

    pdf.set_x(14)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.cell(60, 6, "Recorded Temp / Safe Limit:", 0, 0)
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(120, 6, f"{batch.get('max_recorded_temp_c', 0.0)}°C (Safe Limit <= {batch.get('safe_temp_limit_c', 4.0)}°C)", 0, 1)

    pdf.set_x(14)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.cell(60, 6, "Cold-Chain Fleet Required:", 0, 0)
    pdf.set_font('Helvetica', '', 10)
    pdf.cell(120, 6, "YES (Partner Cold-Chain Fleet Verified)" if partner.get("has_cold_chain") else "NO (Standard Transit Safe)", 0, 1)

    pdf.ln(12)
    pdf.set_font('Helvetica', 'B', 11)
    pdf.cell(0, 8, "Mandatory FSSAI Compliance Declarations:", 0, 1)
    pdf.set_font('Helvetica', '', 9)
    pdf.multi_cell(0, 5, 
        "1. The surplus food listed has been inspected, logged, and confirmed unadulterated in accordance with the Food Safety and Standards (Recovery & Distribution of Surplus Food) Regulations.\n"
        "2. Temperature integrity and remaining shelf life guarantee safety through dispatch and distribution.\n"
        "3. Recipient partner agrees to distribute this food strictly free of charge to beneficiaries without resale."
    )

    pdf.ln(15)
    y_sig = pdf.get_y()
    pdf.line(14, y_sig, 80, y_sig)
    pdf.line(125, y_sig, 190, y_sig)
    pdf.set_xy(14, y_sig + 2)
    pdf.set_font('Helvetica', 'I', 9)
    pdf.cell(66, 6, "Authorized Dispatch Officer", 0, 0, 'C')
    pdf.set_xy(125, y_sig + 2)
    pdf.cell(65, 6, "Authorized NGO Receiving Agent", 0, 1, 'C')

    file_name = f"MANIFEST-{manifest_id}.pdf"
    file_path = os.path.join(MANIFEST_DIR, file_name)
    pdf.output(file_path)
    return f"/static/manifests/{file_name}"

def send_rescue_notification_email(subject: str, body: str):
    """Sends optional notification via SMTP; skips gracefully if credentials not provided"""
    smtp_email = os.getenv("SMTP_EMAIL", "").strip()
    smtp_pwd = os.getenv("SMTP_APP_PASSWORD", "").strip()
    if not smtp_email or not smtp_pwd:
        return
    try:
        msg = MIMEMultipart()
        msg['From'] = smtp_email
        msg['To'] = smtp_email
        msg['Subject'] = f"[ZeroSpoil Alert] {subject}"
        msg.attach(MIMEText(body, 'html'))
        with smtplib.SMTP_SSL("smtp.gmail.com", 465) as server:
            server.login(smtp_email, smtp_pwd)
            server.send_message(msg)
    except Exception as e:
        print(f"SMTP Notification skipped/failed: {e}")

async def mutate_apply_dynamic_markdown(batch: Dict[str, Any], new_price: float, discount_pct: int) -> Dict[str, Any]:
    """Updates batch price in inventory_batches and publishes card to community_deals"""
    batch_id = batch["batch_id"]
    await db.inventory_batches.update_one(
        {"batch_id": batch_id},
        {"$set": {
            "current_price": new_price,
            "status": "MARKED_DOWN",
            "last_action": f"Marked down {discount_pct}% to ₹{new_price}"
        }}
    )

    deal_doc = {
        "_id": f"DEAL-{batch_id}",
        "batch_id": batch_id,
        "merchant_name": batch.get("merchant_name", "FreshMart Supermarket"),
        "merchant_type": batch.get("merchant_type", "SUPERMARKET"),
        "location": batch.get("location", "Panvel Sector 12"),
        "item_summary": batch.get("sku_name", "Clearance Item"),
        "original_price": batch.get("retail_price", new_price),
        "clearance_price": new_price,
        "discount_pct": discount_pct,
        "quantity_remaining": batch.get("quantity", 1),
        "unit": batch.get("unit", "units"),
        "ngo_free_eligible": False,
        "source_channel": "SUPERMARKET_POS_AUDIT",
        "raw_input_preview": f"7:00 PM Automated Audit markdown ({discount_pct}% off)",
        "status": "ACTIVE",
        "created_at": datetime.now(timezone.utc).isoformat()
    }
    await db.community_deals.update_one({"_id": deal_doc["_id"]}, {"$set": deal_doc}, upsert=True)
    return deal_doc

async def mutate_book_ngo_donation(batch: Dict[str, Any], partner: Dict[str, Any]) -> str:
    """Updates batch to DONATED and generates FSSAI PDF manifest"""
    batch_id = batch["batch_id"]
    manifest_id = f"{batch_id}-{int(datetime.now().timestamp())}"
    pdf_url = generate_fssai_manifest(manifest_id, batch, partner)

    await db.inventory_batches.update_one(
        {"batch_id": batch_id},
        {"$set": {
            "status": "DONATED",
            "current_price": 0,
            "donation_partner": partner.get("name"),
            "manifest_pdf_url": pdf_url
        }}
    )

    deal_doc = {
        "_id": f"DEAL-NGO-{batch_id}",
        "batch_id": batch_id,
        "merchant_name": batch.get("merchant_name", "FreshMart Supermarket"),
        "merchant_type": batch.get("merchant_type", "SUPERMARKET"),
        "location": batch.get("location", "Panvel Sector 12"),
        "item_summary": f"[FREE NGO CLAIM] {batch.get('sku_name')}",
        "original_price": batch.get("retail_price", 0),
        "clearance_price": 0,
        "discount_pct": 100,
        "quantity_remaining": batch.get("quantity", 1),
        "unit": batch.get("unit", "units"),
        "ngo_free_eligible": True,
        "source_channel": "NGO_RESCUE_DISPATCH",
        "raw_input_preview": f"Dispatched to {partner.get('name')}",
        "manifest_pdf_url": pdf_url,
        "status": "ACTIVE",
        "created_at": datetime.now(timezone.utc).isoformat()
    }
    await db.community_deals.update_one({"_id": deal_doc["_id"]}, {"$set": deal_doc}, upsert=True)
    send_rescue_notification_email(
        f"NGO Dispatch: {batch.get('sku_name')}",
        f"<p>Batch {batch_id} allocated to <b>{partner.get('name')}</b>.</p><p><a href='{pdf_url}'>View FSSAI Manifest</a></p>"
    )
    return pdf_url

async def mutate_route_to_biogas(batch: Dict[str, Any], reason: str) -> None:
    """Updates batch status to BIOGAS_COMPOST due to safety hard-block"""
    batch_id = batch["batch_id"]
    await db.inventory_batches.update_one(
        {"batch_id": batch_id},
        {"$set": {
            "status": "BIOGAS_COMPOST",
            "current_price": 0,
            "rejection_reason": reason
        }}
    )

async def rollback_batch_mutation(batch_id: str, pre_snapshot: Dict[str, Any]) -> bool:
    """Rolls back batch to its previous snapshot and cleans up community deal"""
    if pre_snapshot:
        await db.inventory_batches.update_one({"batch_id": batch_id}, {"$set": pre_snapshot})
    await db.community_deals.delete_one({"_id": f"DEAL-{batch_id}"})
    await db.community_deals.delete_one({"_id": f"DEAL-NGO-{batch_id}"})
    return True
